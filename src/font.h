inline void draw_char(SDL_Renderer* renderer, char c, int x, int y, SDL_Color color, int scale = 1) {
    if (c < 32 || c > 126) c = ' ';
    const uint8_t* glyph = FONT_5X7[c - 32];
    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
    for (int col = 0; col < 5; col++) {
        uint8_t line = glyph[col];
        for (int row = 0; row < 7; row++) {
            if ((line >> row) & 1) {
                if (scale == 1) {
                    SDL_RenderDrawPoint(renderer, x + col, y + row);
                } else {
                    SDL_Rect pixel = {x + col * scale, y + row * scale, scale, scale};
                    SDL_RenderFillRect(renderer, &pixel);
                }
            }
        }
    }
}

inline void draw_string(SDL_Renderer* renderer, const std::string& str, int x, int y, SDL_Color color, int scale = 1) {
    int cur_x = x;
    int cur_y = y;
    for (char c : str) {
        if (c == '\n') {
            cur_x = x;
            cur_y += 9 * scale;
            continue;
        }
        draw_char(renderer, c, cur_x, cur_y, color, scale);
        cur_x += 6 * scale; 
    }
}

inline int get_string_width(const std::string& str, int scale = 1) {
    int max_w = 0;
    int cur_w = 0;
    for (char c : str) {
        if (c == '\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0;
        } else {
            cur_w += 6 * scale;
        }
    }
    return (cur_w > max_w ? cur_w : max_w);
}

